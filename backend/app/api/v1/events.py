import json
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from backend.app.database.session import get_db
from backend.app.models.db_models import EventModel
from backend.app.schemas.api_schemas import EventCreate, EventResponse

router = APIRouter(prefix="/events", tags=["Detection Events"])

@router.get("", response_model=List[EventResponse])
def query_events(
    camera_id: Optional[str] = Query(None, description="Filter by camera ID"),
    severity: Optional[str] = Query(None, description="Filter by severity (INFO, WARNING, CRITICAL)"),
    event_type: Optional[str] = Query(None, description="Filter by event type"),
    limit: int = Query(50, ge=1, le=500, description="Max results to return"),
    db: Session = Depends(get_db)
):
    """Query historical video analytics detection events with filters."""
    query = db.query(EventModel)
    if camera_id:
        query = query.filter(EventModel.camera_id == camera_id)
    if severity:
        query = query.filter(EventModel.severity == severity.upper())
    if event_type:
        query = query.filter(EventModel.event_type == event_type.upper())

    return query.order_by(EventModel.created_at.desc()).limit(limit).all()

@router.post("", response_model=EventResponse, status_code=status.HTTP_201_CREATED)
def record_event(event_in: EventCreate, db: Session = Depends(get_db)):
    """Record a system event generated by the AI processing pipeline."""
    details_str = json.dumps(event_in.details) if event_in.details else None
    
    event_record = EventModel(
        event_id=event_in.event_id,
        event_type=event_in.event_type,
        camera_id=event_in.camera_id,
        track_id=event_in.track_id,
        object_type=event_in.object_type,
        confidence=event_in.confidence,
        severity=event_in.severity,
        timestamp=event_in.timestamp,
        iso_timestamp=event_in.iso_timestamp,
        details_json=details_str
    )
    db.add(event_record)
    db.commit()
    db.refresh(event_record)
    return event_record

@router.get("/{event_id}", response_model=EventResponse)
def get_event_by_id(event_id: str, db: Session = Depends(get_db)):
    """Retrieve details for a specific detection event."""
    event = db.query(EventModel).filter(EventModel.event_id == event_id).first()
    if not event:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Event not found.")
    return event
